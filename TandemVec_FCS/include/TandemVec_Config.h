struct TandemVecParams
{
    // ===== 推进系统 ===========================================
    // 来源: models/aircraft-model.json §推进
    float kT;    // N·s²     推力系数  T = kT·ω²
    float kQ;    // N·m·s²   反扭系数  τ = kQ·ω²  (稳态 ω̇=0)
    float Jp;    // kg·m²    桨+转子转动惯量（用于陀螺项与反扭瞬态 τ=kQ·ω²+Jp·ω̇）
    float wMax;  // rad/s    最大转速
    float a;     // m        前电机到质心距离（推力臂，正值）
    float b;     // m        尾电机到质心距离（推力臂，正值）
    float tauM;  // s        电机一阶滞后时间常数

    // ===== 惯量 / 执行机构 ====================================
    // 来源: 组件级别估算 (2212×2+9047×2+3S电池+碳管框架, 总长63cm, ~600g)
    //   Iy=Iz ≈ 2×0.065×0.315²(电机) + 2×0.012×0.315²(桨) + 0.15×(0.63²/12)(框架)
    //         ≈ 0.0129 + 0.0024 + 0.0050 + 0.0020(舵机) ≈ 0.022 kg·m²
    //   Ix ≈ m_motor×r²/2 + m_batt×r²/2 ≈ 0.0013 + 0.0006 ≈ 0.0021 kg·m²
    float Ix;    // kg·m²    机体滚转惯量（绕纵轴=差速航向轴）
    float Iy;    // kg·m²    机体俯仰惯量
    float Iz;    // kg·m²    机体偏航/侧倾惯量
    float dMax;  // rad      摆角限幅（±25°）

    // ===== 控制分配专用 =======================================
    // 来源: models/aircraft-model.json §SAS 增稳
    float dwMax; // -        差速指令限幅 Δω ∈ [-dwMax, +dwMax]

    // ===== 质量 / 重力 ========================================
    // 来源: models/aircraft-model.json §质量 / 气动
    float m;     // kg       质量
    float g;     // m/s²     重力加速度
};

// ============================================================
//  ServoConfig — 舵机标定参数（首飞前必须核查，不影响控制算法逻辑）
//
//  标定流程：
//    1. dir_pitch / dir_roll：手动TVC模式，推pitch/roll摇杆观察摆座方向；
//       若摆向与期望相反，将对应值从 +1.f 改为 -1.f。
//    2. half_travel_deg：手动TVC模式推满行程（摆座到25°），量舵机实际
//       转过角度 s_deg；则 half_travel_deg = s_deg / (25/45) ≈ s_deg × 1.8。
//    3. zero_pitch_pct / zero_roll_pct：摇杆归中时若摆座不在 0°，
//       调整偏置（正值向正方向偏）直到目视归零。单位：百分比（%）。
// ============================================================
struct ServoConfig
{
    float teeth_servo;       // 舵机齿轮齿数（当前硬件：30T）
    float teeth_gimbal;      // 摆座齿轮齿数（当前硬件：40T）
    float half_travel_deg;   // 舵机半行程（°）。待实机标定，默认 45°。

    // 方向：+1.0f = 正摆角→PWM > 50%；-1.0f = 正摆角→PWM < 50%
    // 取决于舵臂安装方位，地面通电后手动 TVC 核查
    float dir_pitch;         // 下摆（俯仰）舵机方向  ← ⚠️ 待核查
    float dir_roll;          // 上摆（侧倾）舵机方向  ← ⚠️ 待核查

    // 机械中位偏置（%）：补偿安装误差导致的舵机零点偏移
    // 调整后摇杆归中时摆座应目视在 0°
    float zero_pitch_pct;    // 下摆舵机中位偏置  ← 待标定，初始值 0
    float zero_roll_pct;     // 上摆舵机中位偏置  ← 待标定，初始值 0
};

